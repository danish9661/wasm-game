#!/usr/bin/env python3
"""Compose labeled contact sheets from the per-model audit renders.

    python3 scripts/compose_character_sheet.py [label]

Sheets:
  assets/qa/characters/<label>/sheet_gameplay.png  (characters ~66 px tall)
  assets/qa/characters/<label>/sheet_zoom.png      (characters ~155 px tall)
Each cell carries a 1.55 u grey human silhouette at the SAME scale.
"""
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
QA = ROOT / "assets" / "qa" / "characters"
label = sys.argv[1] if len(sys.argv) > 1 else "before"
family = json.loads((QA / "family.json").read_text())["family"]

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
FONT_BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"


def font(size, bold=False):
    try:
        return ImageFont.truetype(FONT_BOLD if bold else FONT, size)
    except OSError:
        return ImageFont.load_default()


def compose(scale, cols=6):
    src = QA / label / scale
    files = [(e, src / (e["name"] + ".png")) for e in family]
    files = [(e, p) for e, p in files if p.exists()]
    if not files:
        raise SystemExit("no renders in %s" % src)
    cw, ch = Image.open(files[0][1]).size
    pad, bar, top = 6, 26, 62
    rows = (len(files) + cols - 1) // cols
    W = cols * (cw + pad) + pad
    H = top + rows * (ch + bar + pad) + pad + 34
    sheet = Image.new("RGB", (W, H), (28, 30, 33))
    d = ImageDraw.Draw(sheet)
    title = ("CHARACTER FAMILY — %s scale | 1u = 1 tile, player 1.55u | "
             "grey silhouette = 1.55u human" % scale.upper())
    d.text((pad + 4, 8), title, fill=(238, 240, 243), font=font(20, True))
    sub = ("%d models | orthographic yaw 45° / pitch 30° | flat-shaded palette | "
           "each cell shows the model beside a same-scale human" % len(files))
    d.text((pad + 4, 36), sub, fill=(160, 168, 178), font=font(13))
    for i, (e, p) in enumerate(files):
        col, row = i % cols, i // cols
        x = pad + col * (cw + pad)
        y = top + row * (ch + bar + pad)
        img = Image.open(p).convert("RGB")
        sheet.paste(img, (x, y))
        d.rectangle((x, y + ch, x + cw, y + ch + bar), fill=(40, 43, 48))
        label_text = e["name"]
        f = font(13, True)
        while d.textlength(label_text, font=f) > cw - 78 and f.size > 9:
            f = font(f.size - 1, True)
        d.text((x + 5, y + ch + 5), label_text, fill=(240, 242, 245), font=f)
        info = "%.2fu %dt" % (e["height"], e["triangles"])
        fi = font(11)
        d.text((x + cw - d.textlength(info, font=fi) - 5, y + ch + 7),
               info, fill=(155, 163, 172), font=fi)
    d.text((pad + 4, H - 27),
           "Evidence: assets/qa/characters/%s/ | generated by "
           "scripts/blender/render_character_audit.py" % label,
           fill=(130, 138, 148), font=font(12))
    out = QA / label / ("sheet_%s.png" % scale)
    sheet.save(out)
    print("SHEET", out.relative_to(ROOT), sheet.size)


if __name__ == "__main__":
    compose("gameplay")
    compose("zoom")
