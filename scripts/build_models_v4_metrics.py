#!/usr/bin/env python3
"""Generate docs/MODELS_V4_METRICS.md from the wave-4 export data.

Measurements come from ``assets/models/expansion_models_v4.json`` (written by
``scripts/blender/gen_models_v4.py`` after each GLB export) and are
cross-checked against ``assets/models/metrics.json`` (written by
``scripts/verify_models.py``). Every height ratio is measured/1.55.

Run: python3 scripts/build_models_v4_metrics.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODELS = ROOT / "assets" / "models"
OUT = ROOT / "docs" / "MODELS_V4_METRICS.md"
PLAYER = 1.55


def load(name):
    return json.loads((MODELS / name).read_text(encoding="utf-8"))


def fmt(v):
    return ("%.3f" % v).rstrip("0").rstrip(".")


def dims(rec):
    m = rec["measured"]
    return "%s x %s x %s" % (fmt(m["width"]), fmt(m["depth"]), fmt(m["height"]))


def table(recs):
    lines = [
        "| Asset | Measured W x D x H (u) | x1.55 player | Tris | Role | Notes |",
        "|---|---:|---:|---:|---|---|",
    ]
    for r in sorted(recs, key=lambda x: x["name"]):
        parts = r["notes"].split("; ", 1)
        role = parts[0].replace("|", "/")
        notes = parts[1].replace("|", "/") if len(parts) > 1 else ""
        if r["hero"]:
            notes += " (**hero**)"
        lines.append("| `%s` | %s | %.2fx | %d | %s | %s |" % (
            r["name"], dims(r), r["ratio_to_player"], r["triangles"],
            role, notes))
    return "\n".join(lines)


def main():
    records = load("expansion_models_v4.json")["assets"]
    verify = load("metrics.json")
    by_name = {m["name"]: m for m in verify["models"]}
    for r in records:
        v = by_name.get(r["name"])
        if (v is None or not v["pass"]
                or v["triangles"] != r["triangles"]
                or abs(v["height"] - r["measured"]["height"]) > 0.001):
            raise SystemExit("wave-4 metrics mismatch: %s" % r["name"])

    members = {
        "dungeon": {"dungeon_stairs", "dungeon_cage", "dungeon_lever",
                    "dungeon_rack", "coffin_stack", "dungeon_broken_pillar",
                    "dungeon_floor_grate", "dungeon_crank", "barred_door",
                    "dungeon_arch", "dungeon_treasury_interior"},
        "farm_town": {"haystack", "hay_bale", "chicken_coop", "water_trough",
                      "apple_tree", "farm_windmill", "town_fountain",
                      "market_umbrella", "market_scale", "inn_sign",
                      "street_bollard", "town_clock"},
        "ocean": {"ship_wheel", "rope_coil", "fishing_rod", "life_ring",
                  "dock_bollard", "ship_lantern", "shell_cluster", "driftwood"},
        "npc": {"npc_mayor", "npc_priest", "npc_bard", "npc_hunter",
                "npc_fisher", "npc_farmer", "npc_captain", "npc_apprentice",
                "npc_sailor", "npc_mermaid"},
        "new": {"ruin_colonnade", "ruin_wall", "broken_obelisk", "ruin_steps",
                "farm_cart", "rowboat", "handcart", "forest_deer",
                "river_otter", "sea_turtle"},
    }
    grouped = {key: [] for key in members}
    for r in records:
        for key, names in members.items():
            if r["name"] in names:
                grouped[key].append(r)
                break

    families = [
        ("dungeon", "Wave 4A - Dungeon structures & interior",
         "Eleven structural pieces plus an assembled 4x4 treasury. These "
         "extend wave 3's crypt props: cellars, cages, mechanisms, a barred "
         "door, an arch and a vaulted store room. No name repeats the earlier "
         "`dungeon_*`, `altar`, `sarcophagus` or `bone_pile*` assets."),
        ("farm_town", "Wave 4B - Farm & town props",
         "Twelve more harvest, stall and street pieces. They complement the "
         "wave-3 crops/furniture without reusing `wheat`, `well_bucket`, "
         "`bench`, `street_lamp` or either barrel variant."),
        ("ocean", "Wave 4C - Ocean props",
         "Eight deck, tackle and beach pieces. New families alongside the "
         "existing `anchor`, `buoy`, `dock_plank` and coral variants."),
        ("npc", "Wave 4D - Ten more NPC variants",
         "Ten unique humanoid silhouettes at the 1.55 u player scale, "
         "spanning 1.08x-1.28x. Distinct from all earlier NPC variants."),
        ("new", "Wave 4E - New families: ruins, vehicles, creatures",
         "Ten assets opening three new categories. The ruins use the same "
         "stone palette as the earlier kit; the vehicles and creatures are "
         "low-poly silhouettes built from the same shared primitives."),
    ]

    out = [
        "# Starfall - Model wave 4 metrics",
        "",
        "Generated by `python3 scripts/build_models_v4_metrics.py` from "
        "`assets/models/expansion_models_v4.json`, the per-asset measurements "
        "written by `scripts/blender/gen_models_v4.py` after each GLB export. "
        "Numbers are cross-checked against `assets/models/metrics.json`.",
        "",
        "## Scale contract",
        "",
        "- **1 unit = 1 tile = 1 metre.** Blender is Z-up; exported glTF is "
        "Y-up. The tables give **W x D x H** in glTF axes "
        "(X footprint x Z footprint x Y height).",
        "- Player reference: **1.55 u** (`player.glb` measures 1.55 u). "
        "Every ratio is `measured height / 1.55`.",
        "- Storey height **2.5 u**; doors **0.9 x 2.0 u**; grid pitch "
        "**1 u**. `dungeon_treasury_interior` is 2.52 u tall (bevelled "
        "capital) and `barred_door` is 2.08 u.",
        "- Every asset's lowest point is exactly **y = 0** and its footprint "
        "centre is exactly **(x, z) = (0, 0)** in the exported GLB.",
        "- Flat-shaded, palette-only Principled materials, low-poly, no "
        "textures. Triangle budget **500 per prop/NPC/creature**, **1500 for "
        "the assembled `dungeon_treasury_interior`**.",
        "- No names duplicate the 171 GLBs that existed before wave 4.",
        "",
        "## Verification summary",
        "",
        "- `python3 scripts/verify_models.py`: **%d GLBs, %d passed, %d "
        "failed**, %d triangles total (was 171 GLBs / 40102 triangles before "
        "wave 4)." % (
            verify["summary"]["models"], verify["summary"]["passed"],
            verify["summary"]["failed"], verify["summary"]["total_triangles"]),
        "- `python3 scripts/check_metrics.py`: all invariants hold "
        "(player 1.55 u, house within 2-4 u, every base Y ~= 0, budgets "
        "respected).",
        "- Wave 4 adds **%d models / %d triangles**; the largest non-hero "
        "asset is %d tris and the assembled interior is %d tris." % (
            len(records), sum(r["triangles"] for r in records),
            max(r["triangles"] for r in records if not r["hero"]),
            next(r["triangles"] for r in records if r["hero"])),
        "- Cross-check: all %d wave-4 heights and triangle counts in this "
        "document match `assets/models/metrics.json`." % len(records),
        "",
    ]

    for key, title, blurb in families:
        recs = grouped[key]
        out += ["## " + title, "", blurb, "", table(recs), "",
                "All %d models in this family pass `verify_models.py` with "
                "base Y = 0 and centre (0, 0)." % len(recs), ""]

    hero = next(r for r in records if r["hero"])
    out += [
        "## Hero interior composition",
        "",
        "| Interior | Footprint (u) | Height (u) | x1.55 player | Tris | "
        "Composition |",
        "|---|---:|---:|---:|---:|---|",
        "| `%s` | %s x %s | %s | %.2fx | %d | "
        "4x4 stone floor, sixteen 1 u wall segments on the ±2 grid lines "
        "(3 courses each), barred 0.9x2.0 door + transom, two pillars, three "
        "strongboxes, three bullion heaps and two torches |" % (
            hero["name"], fmt(hero["measured"]["width"]),
            fmt(hero["measured"]["depth"]), fmt(hero["measured"]["height"]),
            hero["ratio_to_player"], hero["triangles"]),
        "",
        "The vault uses the same 1 u grid convention as the earlier kit "
        "interiors. Its selective bevel (floor slab and chest lids), weighted "
        "normals and smart UV pack follow the game-asset-modeling finishing "
        "path.",
        "",
        "## Reproduce",
        "",
        "```bash",
        "~/.local/blender/blender -b --python scripts/blender/gen_models_v4.py",
        "python3 scripts/verify_models.py",
        "python3 scripts/check_metrics.py",
        "python3 scripts/build_models_v4_metrics.py",
        "```",
        "",
        "Style contract: `docs/ART_DIRECTION.md` and `assets/spec.json`. "
        "Prior waves: `docs/MODELS_V3_METRICS.md` and "
        "`docs/EXPANSION_METRICS.md`.",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print("WROTE", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
