#!/usr/bin/env python3
"""Generate docs/MODELS_V3_METRICS.md from the wave-3 export data.

Measurements come from ``assets/models/expansion_models_v3.json`` (written by
``scripts/blender/gen_models_v3.py`` after each GLB export) and are
cross-checked against ``assets/models/metrics.json`` (written by
``scripts/verify_models.py``). Every height ratio is measured/1.55.

Run: python3 scripts/build_models_v3_metrics.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODELS = ROOT / "assets" / "models"
OUT = ROOT / "docs" / "MODELS_V3_METRICS.md"
PLAYER = 1.55


def load(name):
    return json.loads((MODELS / name).read_text(encoding="utf-8"))


def fmt(v):
    return ("%.3f" % v).rstrip("0").rstrip(".")


def dims(rec):
    m = rec["measured"]
    return "%s x %s x %s" % (fmt(m["width"]), fmt(m["depth"]), fmt(m["height"]))


def table(recs):
    lines = [
        "| Asset | Measured W x D x H (u) | x1.55 player | Tris | Role | Notes |",
        "|---|---:|---:|---:|---|---|",
    ]
    for r in sorted(recs, key=lambda x: x["name"]):
        parts = r["notes"].split("; ", 1)
        role = parts[0].replace("|", "/")
        notes = parts[1].replace("|", "/") if len(parts) > 1 else ""
        if r["hero"]:
            notes += " (**hero**)"
        lines.append("| `%s` | %s | %.2fx | %d | %s | %s |" % (
            r["name"], dims(r), r["ratio_to_player"], r["triangles"],
            role, notes))
    return "\n".join(lines)


def main():
    records = load("expansion_models_v3.json")["assets"]
    verify = load("metrics.json")
    by_name = {m["name"]: m for m in verify["models"]}
    for r in records:
        v = by_name.get(r["name"])
        if (v is None or not v["pass"]
                or v["triangles"] != r["triangles"]
                or abs(v["height"] - r["measured"]["height"]) > 0.001):
            raise SystemExit("wave-3 metrics mismatch: %s" % r["name"])

    families = [
        ("dungeon", "Wave 3A - Dungeon interiors & props",
         "Eight pieces for crypts and cells. These are new silhouettes, not "
         "copies of the existing `altar`, `bone_pile` or `dungeon_room`: "
         "`dungeon_altar` is a smaller cold-stone offering table, the two "
         "bone piles are a rib cage and a skull heap, and "
         "`dungeon_cell_interior` is an assembled 3x3 cell built from the "
         "same 1 u grid as the earlier interiors."),
        ("farm", "Wave 3B - Farm & crops",
         "Six harvest and field pieces. `well_bucket` is a distinct winch-and-"
         "bucket variant of the existing `well`; `fence_gate` is a separate "
         "asset from the straight `fence`."),
        ("town", "Wave 3C - Town furniture",
         "Six dressing pieces for the existing market and street kit. "
         "`market_goods` sits on a `market_stall`; the two barrel variants "
         "differ from the closed `barrel`."),
        ("ocean", "Wave 3D - Ocean props",
         "Six mooring, navigation and wreck pieces. `coral_fan` and "
         "`coral_brain` are new colonies, not a reuse of `coral`; "
         "`dock_plank` is a dock section, not the single `wreck_plank`."),
        ("npc", "Wave 3E - Four more NPC variants",
         "Four townsfolk at human scale. Each is a unique silhouette and "
         "does not repeat `npc_merchant`, `npc_guard`, `npc_elder` or "
         "`npc_villager_child`."),
    ]
    # The generator stores a short role in each record's `family` field, so
    # group by the explicit wave-3 name sets here rather than by that field.
    members = {
        "dungeon": {"dungeon_altar", "sarcophagus", "torch_sconce",
                    "dungeon_chains", "dungeon_gate", "bone_pile_ribs",
                    "bone_pile_skulls", "dungeon_cell_interior"},
        "farm": {"wheat", "carrot", "potato", "fence_gate", "scarecrow",
                 "well_bucket"},
        "town": {"market_goods", "bench", "street_lamp", "signpost",
                 "barrel_stacked", "barrel_open"},
        "ocean": {"anchor", "buoy", "shipwreck_mast", "dock_plank",
                  "coral_fan", "coral_brain"},
        "npc": {"npc_blacksmith", "npc_innkeeper", "npc_child_urchin",
                "npc_traveling_scholar"},
    }
    grouped = {key: [] for key in members}
    for r in records:
        for key, names in members.items():
            if r["name"] in names:
                grouped[key].append(r)
                break

    out = [
        "# Starfall - Model wave 3 metrics",
        "",
        "Generated by `python3 scripts/build_models_v3_metrics.py` from "
        "`assets/models/expansion_models_v3.json`, the per-asset measurements "
        "written by `scripts/blender/gen_models_v3.py` after each GLB export. "
        "Numbers are cross-checked against `assets/models/metrics.json`.",
        "",
        "## Scale contract",
        "",
        "- **1 unit = 1 tile = 1 metre.** Blender is Z-up; exported glTF is "
        "Y-up. The tables give **W x D x H** in glTF axes "
        "(X footprint x Z footprint x Y height).",
        "- Player reference: **1.55 u** (`player.glb` measures 1.55 u). "
        "Every ratio is `measured height / 1.55`.",
        "- Storey height **2.5 u**; doors **0.9 x 2.0 u**; windows "
        "**0.8 x 0.9 u** raised to a **1.1 u** sill; grid pitch **1 u**; "
        "street lamp **3.0 u** (`street_lamp` measures 3.06 u).",
        "- Every asset's lowest point is exactly **y = 0** and its footprint "
        "centre is exactly **(x, z) = (0, 0)** in the exported GLB.",
        "- Flat-shaded, palette-only Principled materials, low-poly, no "
        "textures. Triangle budget **500 per prop/NPC**, **1500 for the "
        "assembled `dungeon_cell_interior`**.",
        "- No names duplicate the 141 GLBs that existed before wave 3.",
        "",
        "## Verification summary",
        "",
        "- `python3 scripts/verify_models.py`: **%d GLBs, %d passed, %d "
        "failed**, %d triangles total (was 141 GLBs / 33468 triangles before "
        "wave 3)." % (
            verify["summary"]["models"], verify["summary"]["passed"],
            verify["summary"]["failed"], verify["summary"]["total_triangles"]),
        "- `python3 scripts/check_metrics.py`: all invariants hold "
        "(player 1.55 u, house within 2-4 u, every base Y ~= 0, budgets "
        "respected).",
        "- Wave 3 adds **%d models / %d triangles**; the largest prop is "
        "%d tris and the assembled interior is %d tris." % (
            len(records), sum(r["triangles"] for r in records),
            max(r["triangles"] for r in records if not r["hero"]),
            next(r["triangles"] for r in records if r["hero"])),
        "- Cross-check: all %d wave-3 heights and triangle counts in this "
        "document match `assets/models/metrics.json`." % len(records),
        "",
    ]

    for key, title, blurb in families:
        recs = grouped[key]
        out += ["## " + title, "", blurb, "", table(recs), "",
                "All %d models in this family pass `verify_models.py` with "
                "base Y = 0 and centre (0, 0)." % len(recs), ""]

    hero = next(r for r in records if r["hero"])
    out += [
        "## Hero interior composition",
        "",
        "| Interior | Footprint (u) | Height (u) | x1.55 player | Tris | "
        "Composition |",
        "|---|---:|---:|---:|---:|---|",
        "| `%s` | %s x %s | %s | %.2fx | %d | "
        "3x3 stone floor, eight 1 u wall segments on the ±1.5 grid lines "
        "(3 courses each), 0.9x2.0 door, barred window at the 1.1 u sill, "
        "hanging chain, stone coffer, torch and bone scatter |" % (
            hero["name"], fmt(hero["measured"]["width"]),
            fmt(hero["measured"]["depth"]), fmt(hero["measured"]["height"]),
            hero["ratio_to_player"], hero["triangles"]),
        "",
        "The cell uses the same 1 u grid convention as the earlier kit: wall "
        "segments sit on the grid lines and tile centres are the integer cell "
        "centres. Its selective bevel (floor slab and coffer lid), weighted "
        "normals and smart UV pack follow the game-asset-modeling finishing "
        "path used by the wave-2 interiors.",
        "",
        "## Reproduce",
        "",
        "```bash",
        "~/.local/blender/blender -b --python scripts/blender/gen_models_v3.py",
        "python3 scripts/verify_models.py",
        "python3 scripts/check_metrics.py",
        "python3 scripts/build_models_v3_metrics.py",
        "```",
        "",
        "Style contract: `docs/ART_DIRECTION.md` and `assets/spec.json`. "
        "Art-direction context: `docs/EXPANSION_METRICS.md`.",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print("WROTE", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
