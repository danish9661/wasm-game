#!/usr/bin/env python3
"""Generate docs/MODELS_V5_METRICS.md from the wave-5 export data.

Measurements come from ``assets/models/expansion_models_v5.json`` (written by
``scripts/blender/gen_models_v5.py`` after each GLB export) and are
cross-checked against ``assets/models/metrics.json`` (written by
``scripts/verify_models.py``). Every player ratio is measured / 1.55.

Run: python3 scripts/build_models_v5_metrics.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODELS = ROOT / "assets" / "models"
OUT = ROOT / "docs" / "MODELS_V5_METRICS.md"
PLAYER = 1.55
BEFORE_MODELS = 223
BEFORE_TRIANGLES = 50946


def load(name):
    return json.loads((MODELS / name).read_text(encoding="utf-8"))


def fmt(v):
    return ("%.3f" % v).rstrip("0").rstrip(".")


def dims(rec):
    m = rec["measured"]
    return "%s x %s x %s" % (fmt(m["width"]), fmt(m["depth"]), fmt(m["height"]))


def table(recs):
    lines = [
        "| Asset | Measured W x D x H (u) | x1.55 player | Tris | Role | Notes |",
        "|---|---:|---:|---:|---|---|",
    ]
    for r in sorted(recs, key=lambda x: x["name"]):
        parts = r["notes"].split("; ", 1)
        role = parts[0].replace("|", "/")
        notes = parts[1].replace("|", "/") if len(parts) > 1 else ""
        if r["hero"]:
            notes += " (**hero**)"
        lines.append("| `%s` | %s | %.2fx | %d | %s | %s |" % (
            r["name"], dims(r), r["ratio_to_player"], r["triangles"],
            role, notes))
    return "\n".join(lines)


def main():
    records = load("expansion_models_v5.json")["assets"]
    verify = load("metrics.json")
    by_name = {m["name"]: m for m in verify["models"]}
    for r in records:
        v = by_name.get(r["name"])
        if (v is None or not v["pass"]
                or v["triangles"] != r["triangles"]
                or abs(v["height"] - r["measured"]["height"]) > 0.001):
            raise SystemExit("wave-5 metrics mismatch: %s" % r["name"])

    members = {
        "biome": {"swamp_reeds", "mangrove_roots", "ice_spire", "frozen_log",
                  "desert_ruin_wall", "sandstone_pillar", "wreck_hull_section",
                  "wreck_rudder", "wreck_debris", "obsidian_spire",
                  "volcanic_bomb", "basalt_columns"},
        "enemy": {"armored_goblin", "wraith_knight", "fire_elemental",
                  "stone_elemental"},
        "town": {"market_crates", "shop_sign", "bench_ornate", "vendor_cart",
                 "street_planter", "hitching_post"},
        "dungeon": {"blood_altar", "chain_hoist", "open_sarcophagus",
                    "portcullis_gate", "crypt_brazier", "bone_chandelier"},
        "interiors": {"tavern_interior", "smithy_interior", "shrine_interior"},
    }
    grouped = {key: [] for key in members}
    for r in records:
        for key, names in members.items():
            if r["name"] in names:
                grouped[key].append(r)
                break
    if sum(len(v) for v in grouped.values()) != len(records):
        raise SystemExit("wave-5 family sets do not cover every new asset")

    families = [
        ("biome", "Wave 5A - Biome variety",
         "Twelve new silhouettes for the swamp, tundra, desert, ocean and "
         "volcanic biomes. None repeats `reed`, `mangrove`, `ice_crystal`, "
         "`dune_rock`, `lava_vent`, `wreck_plank` or `shipwreck_mast`."),
        ("enemy", "Wave 5B - Enemy variants",
         "Four distinct enemies at the player's 1.55 u scale: an armoured "
         "goblin, a crowned wraith and two elementals. None repeats `goblin`, "
         "`wraith`, `golem` or `npc_ice_elemental`."),
        ("town", "Wave 5C - Town props",
         "Six street and market props. They complement `market_goods`, "
         "`market_stall`, `bench`, `sign`, `signpost`, `inn_sign`, `farm_cart` "
         "and `handcart` without reusing their silhouettes."),
        ("dungeon", "Wave 5D - Dungeon props",
         "Six crypt fixtures. They extend `altar`, `dungeon_altar`, "
         "`dungeon_chains`, `sarcophagus`, `dungeon_gate` and `brazier` with "
         "new forms: a chalice altar, a chain hoist, an opened coffin, a "
         "spiked gate, a tripod brazier and a bone chandelier."),
        ("interiors", "Wave 5E - Three complete modular interiors",
         "The three hero rooms: tavern, smithy and shrine. All use the 1 u "
         "kit grid, a 2.5 u storey and a real 0.9 x 2.0 u door (jambs, leaf "
         "and lintel) in the south wall. Each is a self-contained diorama "
         "cutaway that reads from the 45-degree isometric camera."),
    ]

    out = [
        "# Starfall - Model wave 5 metrics",
        "",
        "Generated by `python3 scripts/build_models_v5_metrics.py` from "
        "`assets/models/expansion_models_v5.json`, the per-asset measurements "
        "written by `scripts/blender/gen_models_v5.py` after each GLB export. "
        "Numbers are cross-checked against `assets/models/metrics.json`.",
        "",
        "## Scale contract",
        "",
        "- **1 unit = 1 tile = 1 metre.** Blender is Z-up; exported glTF is "
        "Y-up. The tables give **W x D x H** in glTF axes "
        "(X footprint x Z footprint x Y height).",
        "- Player reference: **%.2f u** (`player.glb` measures 1.55 u). "
        "Every ratio is `measured height / 1.55`." % PLAYER,
        "- Storey height **2.5 u**; doors **0.9 x 2.0 u**; windows raised to "
        "a **1.1 u** sill; grid pitch **1 u**. All three hero interiors "
        "measure exactly **2.50 u** tall.",
        "- Every asset's lowest point is exactly **y = 0** and its footprint "
        "centre is exactly **(x, z) = (0, 0)** in the exported GLB.",
        "- Flat-shaded, palette-only Principled materials, low-poly, no "
        "textures. Triangle budget **500 per prop/NPC/enemy**, **1500 for the "
        "assembled interiors**.",
        "- No names duplicate the %d GLBs that existed before wave 5." % BEFORE_MODELS,
        "",
        "## Verification summary",
        "",
        "- `python3 scripts/verify_models.py`: **%d GLBs, %d passed, %d "
        "failed**, %d triangles total (was %d GLBs / %d triangles before "
        "wave 5)." % (
            verify["summary"]["models"], verify["summary"]["passed"],
            verify["summary"]["failed"], verify["summary"]["total_triangles"],
            BEFORE_MODELS, BEFORE_TRIANGLES),
        "- `python3 scripts/check_metrics.py`: all invariants hold "
        "(player 1.55 u, house within 2-4 u, every base Y ~= 0, budgets "
        "respected).",
        "- Wave 5 adds **%d models / %d triangles**; the largest non-hero "
        "asset is %d tris and the largest assembled interior is %d tris." % (
            len(records), sum(r["triangles"] for r in records),
            max(r["triangles"] for r in records if not r["hero"]),
            max(r["triangles"] for r in records if r["hero"])),
        "- Cross-check: all %d wave-5 heights and triangle counts in this "
        "document match `assets/models/metrics.json`." % len(records),
        "",
    ]

    for key, title, blurb in families:
        recs = grouped[key]
        out += ["## " + title, "", blurb, "", table(recs), "",
                "All %d models in this family pass `verify_models.py` with "
                "base Y = 0 and centre (0, 0)." % len(recs), ""]

    out += [
        "## Hero interior composition",
        "",
        "| Interior | Footprint (u) | Height (u) | x1.55 player | Tris | "
        "Composition |",
        "|---|---:|---:|---:|---:|---|",
    ]
    compositions = {
        "tavern_interior": ("planked 4x4 floor, three timber wall courses on "
                            "the 1 u grid, 0.9x2.0 south door, two windows at "
                            "the 1.1 u sill, bar counter + three stools, two "
                            "round tables with benches and mugs, stone hearth "
                            "with flame, two hanging lanterns"),
        "smithy_interior": ("stone 4x4 floor, three wall courses on the 1 u "
                            "grid, 0.9x2.0 south door, high window, coal forge "
                            "with chimney and flame, anvil + horn on a stump, "
                            "tool rack, water trough, two torches"),
        "shrine_interior": ("pale stone 4x4 floor, three wall courses on the "
                            "1 u grid, 0.9x2.0 south door, two windows, raised "
                            "dais with stepped altar and glowing crystal, two "
                            "candles, two columns, banners, cushions and censer"),
    }
    for r in grouped["interiors"]:
        out.append("| `%s` | %s x %s | %s | %.2fx | %d | %s |" % (
            r["name"], fmt(r["measured"]["width"]),
            fmt(r["measured"]["depth"]), fmt(r["measured"]["height"]),
            r["ratio_to_player"], r["triangles"], compositions[r["name"]]))
    out += [
        "",
        "Each hero is authored as bmesh parts (boxes and faceted frusta), then "
        "finished with the game-asset-modeling quality gates: selective "
        "1-segment bevel on silhouette parts, bmesh normal recalculation, "
        "weighted normals, flat shading and an explicit UV pack. Khronos "
        "glTF-Validator reports 0 errors / 0 warnings for all three; the "
        "Babylon review renders in `assets/review/<id>.png` report 0 engine "
        "errors. Repeated independent fresh-eyes critic passes drove the cutaway "
        "orientation, door opening, fixture support, window clearance and "
        "accent-colour fixes until no major findings remained. Briefs: "
        "`assets/src/env/<id>/brief.json`.",
        "",
        "## Reproduce",
        "",
        "```bash",
        "~/.local/blender/blender -b --python scripts/blender/gen_models_v5.py",
        "python3 scripts/verify_models.py",
        "python3 scripts/check_metrics.py",
        "python3 scripts/build_models_v5_metrics.py",
        "```",
        "",
        "Style contract: `docs/ART_DIRECTION.md` and `assets/spec.json`. "
        "Prior waves: `docs/MODELS_V3_METRICS.md` and "
        "`docs/MODELS_V4_METRICS.md`. See `docs/MODELS_V5_BRIEFS.md` for the "
        "per-asset briefs.",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print("WROTE", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
