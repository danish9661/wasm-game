#!/usr/bin/env python3
"""Generate docs/EXPANSION_METRICS.md from measured export data.

Reads the per-family measurement files written by the Blender generators plus
the GLB verifier's metrics.json, so every number in the document comes from the
exported assets rather than from the generator's intentions.

Run: python3 scripts/build_expansion_metrics.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODELS = ROOT / "assets" / "models"
OUT = ROOT / "docs" / "EXPANSION_METRICS.md"
PLAYER = 1.55


def load(name):
    return json.loads((MODELS / name).read_text(encoding="utf-8"))


def fmt(v):
    return ("%.3f" % v).rstrip("0").rstrip(".")


def dims(rec):
    m = rec["measured"]
    return "%s x %s x %s" % (fmt(m["width"]), fmt(m["depth"]), fmt(m["height"]))


def table(recs, extra_header=""):
    lines = [
        "| Asset | Measured W x D x H (u) | x1.55 player | Tris | %sNotes |" % extra_header,
        "|---|---:|---:|---:|---|",
    ]
    for r in sorted(recs, key=lambda x: x["name"]):
        notes = r["notes"].replace("|", "/")
        if r["hero"]:
            notes += " (**hero**)"
        lines.append("| `%s` | %s | %.2fx | %d | %s |" % (
            r["name"], dims(r), r["ratio_to_player"], r["triangles"], notes))
    return "\n".join(lines)


def main():
    families = [
        ("biome_props", "Family 1 - Biome objects & props",
         "Twelve props for forest, desert, tundra, swamp, volcanic and ocean "
         "biomes. The mangrove is the hero piece (bevel, weighted normals, "
         "smart UV pack)."),
        ("npc_variants", "Family 2 - NPC & creature variants",
         "Ten new silhouettes spanning 0.41x-1.50x the player. The forest "
         "warden mini-boss is the hero piece (selective bevel, weighted "
         "normals, smart UV pack)."),
        ("kit_expansion", "Family 3 - Building & interior kit",
         "Eight grid-snapped modular pieces plus two complete interiors "
         "assembled from the very same piece builders. Both interiors are "
         "hero pieces with a selective bevel and a smart UV pack."),
    ]
    verify = load("metrics.json")
    by_name = {m["name"]: m for m in verify["models"]}

    out = [
        "# Starfall - Expansion metrics",
        "",
        "Generated by `python3 scripts/build_expansion_metrics.py` from the "
        "exported GLBs. Measurements are read from `assets/models/"
        "expansion_<family>.json` (written by the Blender generators after "
        "export) and cross-checked against `assets/models/metrics.json`.",
        "",
        "## Scale contract",
        "",
        "- **1 unit = 1 tile = 1 metre.** Blender is Z-up; exported glTF is "
        "Y-up. The tables give **W x D x H** in glTF axes "
        "(X footprint x Z footprint x Y height).",
        "- Player reference: **1.55 u** (`player.glb` measures 1.55 u). "
        "Every ratio is `measured height / 1.55`.",
        "- Storey height **2.5 u**; doors **0.9 x 2.0 u**; windows "
        "**0.8 x 0.9 u** raised to a **1.1 u** sill; grid pitch **1 u**.",
        "- Every asset's lowest point is exactly **y = 0** and its footprint "
        "centre is exactly **(x, z) = (0, 0)** in the exported GLB.",
        "- Flat shading, palette-only Principled materials, low-poly, no "
        "textures. Triangle budget 500 per prop/piece, 1500 for the assembled "
        "interiors.",
        "",
        "## Verification summary",
        "",
        "- `python3 scripts/verify_models.py`: **%d GLBs, %d passed, %d "
        "failed**, %d triangles total." % (
            verify["summary"]["models"], verify["summary"]["passed"],
            verify["summary"]["failed"], verify["summary"]["total_triangles"]),
        "- `python3 scripts/check_metrics.py`: all invariants hold "
        "(player ~1.55 u, house 2-4 u, every base Y ~= 0, budgets respected).",
        "- Hero engine reviews: Babylon (`tools/review/shoot.mjs` in the "
        "game-asset-modeling skill) rendered front / three-quarter / eye / "
        "iso / iso_context for all four heroes with **0 console errors**; "
        "sheets are in `assets/review/<id>.png`.",
        "- Fresh-eyes critic: three review/fix rounds. Final verdict - "
        "`blacksmith_hall_interior` and `temple_hall_interior` CLEAN; "
        "`mangrove` and `npc_forest_warden` MINORS ONLY. The only remaining "
        "note is that the harness's fixed ~40 m `iso_context` frame renders "
        "standalone props ~25 px tall; this is review framing, not a model "
        "defect (the assets are correct at 1 u = 1 m).",
        "",
    ]

    for key, title, blurb in families:
        recs = load("expansion_%s.json" % key)["assets"]
        out += ["## " + title, "", blurb, ""]
        out.append(table(recs, extra_header="" if key == "kit_expansion" else "Role | "))
        out += ["", "All %d models pass `verify_models.py` with measured base "
                "Y = 0 and centre (0, 0)." % len(recs), ""]

    out += [
        "## Kit grid snapping",
        "",
        "| Piece | Snap rule |",
        "|---|---|",
        "| `kit_floor` | Exactly one 1x1 tile; tile centres at integer (x, z); "
        "floor top = 0.1 u. |",
        "| `kit_wall_wood`, `kit_wall_stone` | One 1 u grid edge of frontage, "
        "0.15 / 0.18 u thick centred on the boundary line, 2.5 u tall; rotate "
        "90 degrees for edges running along Z. |",
        "| `kit_door` | 0.9 u wide (0.05 u gap each side) x 2.0 u tall, centred "
        "on X; add a 0.5 u transom to fill the remaining storey height. |",
        "| `kit_window` | 0.8 x 0.9 u; base at 0, raise in Y by 1.1 u so the "
        "opening spans 1.1-2.0 u inside a 2.5 u wall. Use the cut-out wall "
        "segments `build_wall_wood_window` / `build_wall_stone_window` "
        "(in the kit generator) for a real opening instead of burying the "
        "window in a solid wall. |",
        "| `kit_stairs` | 1 u wide, six 0.25 u treads over a 1.5 u run, rising "
        "1.5 u to a half-level. |",
        "| `kit_roof_gable` | One 1x1 roof cell; ridge runs along Z (Blender Y) "
        "and repeats cell-to-cell; 0.6 u rise. |",
        "| `kit_pillar` | 0.3 sq, 2.5 u tall = one storey; place on grid "
        "intersections. |",
        "",
        "## Assembled interiors",
        "",
        "| Interior | Footprint (u) | Height (u) | x1.55 player | Tris | "
        "Composition |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for name, composition in (
        ("blacksmith_hall_interior",
         "5x4 floor slab, 17 timber wall segments, centred 0.9x2.0 door + "
         "0.5 u transom, 2 windows at 1.1 u sill, forge, anvil, bellows, "
         "tool rack, coal pile, water trough"),
        ("temple_hall_interior",
         "5x5 floor slab, 19 stone wall segments, centred 0.9x2.0 door + "
         "0.5 u transom, 2 windows at 1.1 u sill, 4 pillars, steps, altar, "
         "2 braziers, 1 banner"),
    ):
        m = by_name[name]
        out.append("| `%s` | %s x %s | %s | %.2fx | %d | %s |" % (
            name, fmt(m["footprint_x"]), fmt(m["footprint_z"]),
            fmt(m["height"]), m["height"] / PLAYER, m["triangles"], composition))
    out += [
        "",
        "Both interiors use the same `Frame`-based builders as the standalone "
        "kit (`build_wall_wood` / `build_wall_stone`, `build_door`, "
        "`build_window`, `build_pillar`, ...). Wall segments sit on the grid "
        "lines: a 5-tile span uses integer centres -2..2, a 4-tile span uses "
        "half-integer centres -1.5..1.5. Tile centres are the integer cell "
        "centres of the footprint.",
        "",
        "## Reproduce",
        "",
        "```bash",
        "~/.local/blender/blender -b --python scripts/blender/gen_biome_props.py",
        "~/.local/blender/blender -b --python scripts/blender/gen_npc_variants.py",
        "~/.local/blender/blender -b --python scripts/blender/gen_kit_expansion.py",
        "python3 scripts/verify_models.py",
        "python3 scripts/check_metrics.py",
        "python3 scripts/build_expansion_metrics.py",
        "```",
        "",
        "Hero briefs live in `assets/src/<category>/<id>/brief.json`; their "
        "style contract is `docs/ART_DIRECTION.md` and `assets/spec.json`.",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print("WROTE", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
