"""Generate web/src/generated_poses.rs from assets/models/poses.json.

If no baked pose manifest exists yet, an empty table is emitted and the
renderer keeps using the single rigid player GLB.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
manifest = ROOT / "assets" / "models" / "poses.json"
out = ROOT / "web" / "src" / "generated_poses.rs"

clips = []
if manifest.exists():
    try:
        data = json.loads(manifest.read_text())
        for name, info in data.items():
            frames = info.get("frames") or []
            if frames:
                clips.append((name, [Path(f).stem for f in frames]))
    except Exception as exc:
        raise SystemExit(f"bad poses.json: {exc}")

lines = [
    "// GENERATED by scripts/gen_pose_list.py — do not edit by hand.",
    "pub struct PoseClip {",
    "    pub name: &'static str,",
    "    pub frames: &'static [&'static str],",
    "}",
    "pub const POSE_CLIPS: &[PoseClip] = &[",
]
for name, frames in clips:
    lines.append("    PoseClip {")
    lines.append('        name: "%s",' % name)
    lines.append("        frames: &[")
    lines += ['            "%s",' % f for f in frames]
    lines.append("        ],")
    lines.append("    },")
lines.append("];")
out.write_text("\n".join(lines) + "\n")
print("[gen_pose_list] %d clips -> %s" % (len(clips), out))
